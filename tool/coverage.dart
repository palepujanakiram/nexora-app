// Runs the Flutter tests with coverage and fails if line coverage of lib/ is
// below the minimum.
//
//   dart run tool/coverage.dart            # default minimum: 95%
//   dart run tool/coverage.dart --min 97
//
// Files that no test imports don't appear in lcov.info at all, which would
// hide untested code. So before running, this writes a temporary test that
// imports every file under lib/, making untested files count as 0%.
import 'dart:io';

const _defaultMin = 95.0;
const _helper = 'test/_coverage_all_files_test.dart';
const _lcov = 'coverage/lcov.info';

Future<void> main(List<String> args) async {
  final i = args.indexOf('--min');
  final min = i >= 0 && i + 1 < args.length ? double.parse(args[i + 1]) : _defaultMin;

  _writeImportAllHelper();
  final int code;
  try {
    final test = await Process.start('flutter', ['test', '--coverage'], mode: ProcessStartMode.inheritStdio);
    code = await test.exitCode;
  } finally {
    File(_helper).deleteSync();
  }
  if (code != 0) {
    stderr.writeln('Tests failed (exit code $code).');
    exit(code);
  }

  final files = parseLcov(File(_lcov).readAsLinesSync());
  final hit = files.values.fold<int>(0, (s, f) => s + f.hit);
  final total = files.values.fold<int>(0, (s, f) => s + f.total);
  final pct = total == 0 ? 100.0 : 100 * hit / total;

  final below = files.entries.where((e) => e.value.percent < min).toList()
    ..sort((a, b) => a.value.percent.compareTo(b.value.percent));
  if (below.isNotEmpty) {
    stdout.writeln('\nFiles below ${min.toStringAsFixed(0)}%:');
    for (final e in below) {
      final f = e.value;
      stdout.writeln('  ${f.percent.toStringAsFixed(1).padLeft(5)}%  ${'${f.hit}/${f.total}'.padLeft(7)}  ${e.key}');
    }
  }

  stdout.writeln('\nLine coverage: ${pct.toStringAsFixed(2)}% ($hit/$total lines), minimum ${min.toStringAsFixed(0)}%');
  if (pct < min) {
    stderr.writeln('Coverage is below the minimum.');
    exit(1);
  }
}

void _writeImportAllHelper() {
  final imports = Directory('lib')
      .listSync(recursive: true)
      .whereType<File>()
      .map((f) => f.path.replaceAll(r'\', '/'))
      .where((p) => p.endsWith('.dart'))
      .map((p) => "import 'package:nexora_app/${p.substring('lib/'.length)}';")
      .toList()
    ..sort();
  File(_helper).writeAsStringSync([
    '// Generated by tool/coverage.dart; deleted after the run.',
    '// ignore_for_file: unused_import',
    ...imports,
    '',
    'void main() {}',
    '',
  ].join('\n'));
}

class FileCoverage {
  int hit = 0;
  int total = 0;
  double get percent => total == 0 ? 100 : 100 * hit / total;
}

/// Line coverage per source file from lcov `SF:` / `DA:` records.
Map<String, FileCoverage> parseLcov(List<String> lines) {
  final files = <String, FileCoverage>{};
  FileCoverage? current;
  for (final line in lines) {
    if (line.startsWith('SF:')) {
      current = files.putIfAbsent(line.substring(3), FileCoverage.new);
    } else if (line.startsWith('DA:') && current != null) {
      final parts = line.substring(3).split(',');
      current.total++;
      if (int.parse(parts[1]) > 0) current.hit++;
    }
  }
  return files;
}
